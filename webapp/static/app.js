// The bar and the clock are animated locally at frame rate and resynced from the
// server on every poll. Polling alone gave one visible change per second, because the
// elapsed time was rendered to whole seconds -- so however often it was fetched, the
// text could not move faster than 1 Hz.
let progRaf = null, prog = null;

function renderProgress() {
  if (!prog) return;
  const e = Math.min(prog.seconds, (performance.now() - prog.t0) / 1000 + prog.offset);
  $('#progress').querySelector('i').style.width =
    Math.min(100, (e / prog.seconds) * 100) + '%';
  $('#progtext').textContent =
    `${e.toFixed(1)}s of ${prog.seconds}s · ${prog.done} restarts` +
    (prog.best != null ? ` · best ${money(prog.best)}` : '');
}

function startProgress(seconds) {
  prog = { t0: performance.now(), seconds, done: 0, best: null, offset: 0 };
  const step = () => {
    if (!prog) return;
    renderProgress();
    progRaf = requestAnimationFrame(step);
  };
  step();
}

function stopProgress() {
  if (progRaf) cancelAnimationFrame(progRaf);
  progRaf = null; prog = null;
}

async function pollSolve(jobId, seconds) {
  try {
    const j = await api('/api/solve/' + jobId);
    if (prog) {
      prog.done = j.done; prog.best = j.best;
      // pull the local clock back onto the server's, so it neither drifts nor jumps
      prog.offset = j.elapsed - (performance.now() - prog.t0) / 1000;
      // also paint here: requestAnimationFrame is suspended while the tab is not
      // visible, so this keeps the numbers moving at the poll rate regardless
      renderProgress();
    }
    if (j.status === 'running') return setTimeout(() => pollSolve(jobId, seconds), 400);
    stopProgress();
    $('#solve').disabled = false;
    if (j.status === 'error') { $('#solveerr').textContent = j.error; return; }
    $('#progress').querySelector('i').style.width = '100%';
    S.layout = j.result; S.ref = 'job_' + jobId;
    S.baseline = { dollars: j.result.score.dollars, name: 'this solve' };
    render();
    const rec = j.result.record;
    toast(rec
      ? `NEW RECORD ${money(rec.dollars)}` +
        (rec.beat != null ? ` — beat ${money(rec.beat)}` : ' (first for this model)')
      : 'solved: ' + money(j.result.score.dollars), rec ? 5000 : 2200);
  } catch (e) {
    stopProgress();
    $('#solveerr').textContent = e.message; $('#solve').disabled = false;
  }
}

