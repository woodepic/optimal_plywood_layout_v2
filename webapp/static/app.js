// Label EVERY part. The old rule skipped anything under 9-3/8" long or 2-13/16" wide,
// which silently dropped the dimensions off narrow strips of short parts -- exactly the
// pieces hardest to identify by eye. Text turns to run along the part's long axis and
// is sized to fit; anything still tiny is legible once you zoom, which the grid allows.
function drawPartLabel(svg, p, fill) {
  const horiz = p.len >= p.w;
  const along = horiz ? p.len : p.w;      // room along the baseline
  const across = horiz ? p.w : p.len;     // room across it
  const CHAR = 0.54;                      // mean glyph advance / font size
  let fs = Math.min(across * 0.62, (along * 0.94) / (p.label.length * CHAR));
  fs = Math.max(6, Math.min(44, fs));
  const cx = p.x + p.len / 2, cy = p.y + p.w / 2;
  const t = sv('text', { x: cx, y: cy, 'text-anchor': 'middle',
    'dominant-baseline': 'central', 'font-size': fs, fill: labelInk(fill) });
  if (!horiz) t.setAttribute('transform', `rotate(-90 ${cx} ${cy})`);
  t.textContent = p.label;
  svg.append(t);
}

