// 1/32" units to a readable fraction
function fmt(u) {
  const whole = Math.floor(u / 32); let n = u % 32, d = 32;
  while (n && n % 2 === 0) { n /= 2; d /= 2; }
  return n ? `${whole}-${n}/${d}"` : `${whole}"`;
}
// Palette generated by farthest-point sampling in CIE Lab, then reordered so that
// CONSECUTIVE indices are as far apart as possible. Widths are indexed in sorted order,
// so consecutive indices are the numerically closest widths -- exactly the pair you
// must never confuse. This job has widths 1/32" apart (23-1/8" and 23-3/32"), and they
// land on neighbouring entries. Minimum separation is dE 25.5 over ANY pair.
//
// The colour keys off each PART's own width, not the width of the strip it was ripped
// from. Under non-exact 2-stage a single strip carries parts of many widths, so keying
// off the rip width painted a whole strip one colour and hid every distinction inside
// it -- two colours for a sheet holding a dozen different widths.
//
// Lightness spans a wide range to buy that separation, so part labels pick their ink
// from the fill's luminance rather than assuming a mid-tone background.
const WIDTH_PALETTE = ['#723b3b','#29ff29','#0000eb','#d4ff29','#0000ad','#8fff66','#d429ff','#0cad00','#004eeb','#9bc526','#ad00ad','#66ffa3','#ff29c6','#3d822b','#c96ff6','#ffc629','#0045ad','#eb0000','#29ffff','#eb003f','#29d4ff','#ff7029','#298dff','#92921c','#621c92','#d2e77e','#ff298d','#a9f9be','#a30a66','#72b696','#a30a15','#0e98dd','#ad5c00','#a3c8ff','#ffad66','#3b3b72','#f0d3b2','#f66fc9','#3b724d','#ff667a','#1c7a92','#f9a9e9','#726b3b','#96509b','#b2ecf0','#968cd9','#d98c91','#e0c2d8'];

function widthColor(i) {
  const base = WIDTH_PALETTE[i % WIDTH_PALETTE.length];
  const cycle = Math.floor(i / WIDTH_PALETTE.length);
  if (!cycle) return base;
  const f = Math.pow(0.72, cycle);      // >36 widths: darken, keeping a hex so that
  const n = parseInt(base.slice(1), 16); // labelInk can still read the luminance
  const r = Math.round(((n >> 16) & 255) * f), g = Math.round(((n >> 8) & 255) * f),
        b = Math.round((n & 255) * f);
  return '#' + [r, g, b].map(v => v.toString(16).padStart(2, '0')).join('');
}

function labelInk(hex) {
  const n = parseInt(hex.slice(1), 16);
  const lum = (0.2126 * ((n >> 16) & 255) + 0.7152 * ((n >> 8) & 255)
               + 0.0722 * (n & 255)) / 255;
  return lum > 0.55 ? '#111' : '#fff';
}

