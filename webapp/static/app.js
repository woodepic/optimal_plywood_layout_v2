async function renderRecords(host) {
  const { records } = await api('/api/records');
  const card = el('div', { class: 'card' },
    el('h2', {}, 'Records — best ever found per model, kept automatically'));
  if (!records.length) {
    card.append(el('div', { class: 'muted small' },
      'No records yet. One is written automatically whenever a solve beats the best ' +
      'layout previously found for that model.'));
    host.append(card); return;
  }
  const t = el('table', {}, el('thead', {}, el('tr', {},
    el('th', {}, 'model'), el('th', {}, 'set'), el('th', { class: 'n' }, 'now'),
    el('th', { class: 'n' }, 'when set'), el('th', { class: 'n' }, 'sheets'),
    el('th', { class: 'n' }, 'hours'), el('th', {}, ''))));
  const tb = el('tbody');
  let anyStar = false;
  for (const r of records) {
    if (!r.config_matches) anyStar = true;
    const star = r.config_matches ? '' : '*';
    tb.append(el('tr', { class: r.is_best ? 'sel' : '' },
      el('td', {},
        el('a', { href: '#', onclick: ev => { ev.preventDefault(); open_(r.id); } },
          (r.filename || r.sha) + star),
        el('div', { class: 'small muted' },
          r.config_matches ? 'set under the costs now in the form'
            : `* set under different costs (${r.config_diff.length} differ: ` +
              `${r.config_diff.slice(0, 4).join(', ')}` +
              `${r.config_diff.length > 4 ? '…' : ''})`)),
      el('td', { class: 'small muted' }, new Date(r.when * 1000).toLocaleString()),
      el('td', { class: 'n' }, r.valid ? money(r.dollars) : '—'),
      el('td', { class: 'n muted' },
        r.dollars_when_set != null ? money(r.dollars_when_set) : '—'),
      el('td', { class: 'n' }, r.n_sheets ?? '—'),
      el('td', { class: 'n' }, r.hours != null ? r.hours.toFixed(2) : '—'),
      el('td', { class: 'small' },
        r.is_best ? el('b', { style: 'color:var(--good)' }, 'best now') :
          (r.valid ? '' : el('span', { class: 'muted' }, 'invalid here')))));
  }
  t.append(tb);
  card.append(t);
  card.append(el('div', { class: 'small muted', style: 'margin-top:8px' },
    'Two prices are shown: "now" is the record repriced under the costs currently in ' +
    'the form, "when set" is what it cost under the costs it was found with. ' +
    (anyStar ? 'A * marks a record found under different costs than you have now — ' +
      'its layout is still valid, but it was optimised for a different objective.'
      : 'All records were found under the costs you have now.')));
  host.append(card);
}

async function renderSaved() {
  const host = $('#savedpane'); host.textContent = 'loading…';
  const { layouts } = await api('/api/saved');
  host.textContent = '';
  await renderRecords(host);
  if (!layouts.length) {
    host.append(el('div', { class: 'card muted' },
      'No manually saved layouts yet. Solve one, then Save it — every saved layout ' +
      'is repriced under the costs currently in the form, so they stay comparable.'));
    return;
  }
  const best = Math.min(...layouts.filter(l => l.valid).map(l => l.dollars));
  const t = el('table', {}, el('thead', {}, el('tr', {},
    el('th', {}, 'name'), el('th', { class: 'n' }, 'total'),
    el('th', { class: 'n' }, 'vs best'), el('th', { class: 'n' }, 'sheets'),
    el('th', { class: 'n' }, 'material'), el('th', { class: 'n' }, 'labour'),
    el('th', { class: 'n' }, 'rips'), el('th', { class: 'n' }, 'stops'),
    el('th', { class: 'n' }, 'mitre'), el('th', { class: 'n' }, 'track x'),
    el('th', { class: 'n' }, 'trims'), el('th', {}, ''))));
  const tb = el('tbody');
  for (const l of layouts) {
    if (!l.valid) {
      tb.append(el('tr', {}, el('td', {}, l.name),
        el('td', { class: 'err', colspan: 11 },
          'not valid under the current cost model: ' + l.error)));
      continue;
    }
    const d = l.dollars - best;
    tb.append(el('tr', { class: l.id === (S.ref || '').replace('job_', '') ? 'sel' : '' },
      el('td', {}, el('a', { href: '#', onclick: ev => { ev.preventDefault(); open_(l.id); } },
        l.name), el('div', { class: 'small muted' }, l.filename || '')),
      el('td', { class: 'n' }, money(l.dollars)),
      el('td', { class: 'n' }, d < 0.005 ? '—' :
        el('span', { class: 'delta up' }, '+' + money(d))),
      el('td', { class: 'n' }, l.n_sheets), el('td', { class: 'n' }, money(l.material)),
      el('td', { class: 'n' }, money(l.labour)), el('td', { class: 'n' }, l.n_rips),
      el('td', { class: 'n' }, l.n_track_stops), el('td', { class: 'n' }, l.n_cross),
      el('td', { class: 'n' }, l.n_wide_cross), el('td', { class: 'n' }, l.n_trims),
      el('td', {}, el('button', { class: 'danger small', onclick: async () => {
        await api('/api/saved/' + l.id, { method: 'DELETE' }); renderSaved();
      } }, 'delete'))));
  }
  t.append(tb);
  host.append(el('div', { class: 'card' },
    el('h2', {}, 'Saved layouts, all repriced under the costs in the form'), t,
    el('div', { class: 'small muted', style: 'margin-top:8px' },
      'Click a name to open it. Repricing compares plans fairly under one cost ' +
      'model; it does not tell you the best plan for those costs — Solve does.')));
}

