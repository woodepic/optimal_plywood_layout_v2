// ---------- zoomable grid of sheets ----------
const V = { scale: 1, tx: 0, ty: 0 };

function applyTransform() {
  $('#canvas').style.transform =
    `translate(${V.tx}px,${V.ty}px) scale(${V.scale})`;
  $('#zlabel').textContent = Math.round(V.scale * 100) + '%';
}

function zoomAt(px, py, factor) {
  const next = Math.max(0.05, Math.min(6, V.scale * factor));
  const k = next / V.scale;
  // keep whatever sits under the cursor fixed: solve for the translation that leaves
  // the cursor's canvas-space point where it was
  V.tx = px - k * (px - V.tx);
  V.ty = py - k * (py - V.ty);
  V.scale = next;
  applyTransform();
}

function fitAll(tries = 8) {
  const vp = $('#viewport'), cv = $('#canvas');
  cv.style.transform = 'none';
  const cw = cv.scrollWidth, ch = cv.scrollHeight;
  cv.style.transform = '';
  if (!cw || !ch || !vp.clientWidth) {
    // First call can land before the SVGs have laid out, when the canvas still
    // measures zero. Retry rather than silently leaving the view untransformed.
    if (tries > 0) requestAnimationFrame(() => fitAll(tries - 1));
    return;
  }
  V.scale = Math.min(vp.clientWidth / cw, vp.clientHeight / ch);
  V.tx = (vp.clientWidth - cw * V.scale) / 2;
  V.ty = 0;
  applyTransform();
}

function renderSheets() {
  const cv = $('#canvas'); cv.textContent = '';
  const n = S.layout.sheets.length;
  const pick = parseInt($('#cols').value, 10) || 0;
  const cols = pick || Math.max(1, Math.min(6, Math.ceil(Math.sqrt(n))));
  cv.style.gridTemplateColumns = `repeat(${cols}, max-content)`;
  // sheets arrive in rip-sequence order, so number them by that order -- it is the
  // order you actually cut them in. Labelling by the solver's internal index made the
  // first sheet on screen read "Sheet 14".
  S.layout.sheets.forEach((sh, i) => cv.append(sheetCard(sh, i)));
  // Called synchronously: reading scrollWidth forces layout, so the canvas already has
  // its real size here. The retry inside fitAll covers the case where the pane is
  // hidden and everything still measures zero.
  fitAll();
}

(function wireViewport() {
  const vp = $('#viewport');
  vp.addEventListener('wheel', ev => {
    ev.preventDefault();
    const r = vp.getBoundingClientRect();
    // trackpad pinch arrives as ctrl+wheel; treat both the same
    const f = Math.exp(-ev.deltaY * (ev.ctrlKey ? 0.01 : 0.0022));
    zoomAt(ev.clientX - r.left, ev.clientY - r.top, f);
  }, { passive: false });

  let drag = null;
  vp.addEventListener('pointerdown', ev => {
    drag = { x: ev.clientX, y: ev.clientY, tx: V.tx, ty: V.ty };
    vp.classList.add('drag'); vp.setPointerCapture(ev.pointerId);
  });
  vp.addEventListener('pointermove', ev => {
    if (!drag) return;
    V.tx = drag.tx + (ev.clientX - drag.x);
    V.ty = drag.ty + (ev.clientY - drag.y);
    applyTransform();
  });
  const end = () => { drag = null; vp.classList.remove('drag'); };
  vp.addEventListener('pointerup', end);
  vp.addEventListener('pointercancel', end);

  $('#zfit').onclick = fitAll;
  $('#zone').onclick = () => { V.scale = 1; V.tx = 0; V.ty = 0; applyTransform(); };
  const mid = f => () => {
    const r = vp.getBoundingClientRect();
    zoomAt(r.width / 2, r.height / 2, f);
  };
  $('#zin').onclick = mid(1.25);
  $('#zout').onclick = mid(0.8);
  $('#cols').onchange = () => { if (S.layout) renderSheets(); };
})();

function sheetCard(sh, pos) {
  const M = 26, W = sh.along, H = sh.across;
  const svg = sv('svg', { viewBox: `${-M} ${-M} ${W + 2 * M} ${H + 2 * M}` });

  const defs = sv('defs', {});
  const pat = sv('pattern', { id: 'hatch', width: 12, height: 12,
    patternUnits: 'userSpaceOnUse', patternTransform: 'rotate(45)' });
  pat.append(sv('line', { x1: 0, y1: 0, x2: 0, y2: 12, stroke: '#9a9a9a',
    'stroke-width': 4 }));
  defs.append(pat); svg.append(defs);

  svg.append(sv('rect', { x: 0, y: 0, width: W, height: H, fill: '#fff',
    stroke: '#333', 'stroke-width': 3 }));

  for (const st of sh.strips) {
    // the strip band: shows the width group, and therefore which rips share a stop
    // faint band in the RIP width's colour: still shows which strips share a stop
    svg.append(sv('rect', { x: 0, y: st.y, width: W, height: st.width,
      fill: widthColor(st.color), opacity: 0.14 }));
    for (const p of st.parts) {
      const fill = widthColor(p.color);
      svg.append(sv('rect', { x: p.x, y: p.y, width: p.len, height: p.w,
        fill, stroke: '#1f1f1f', 'stroke-width': 1.5 }));
      drawPartLabel(svg, p, fill);
      if (p.trim) {
        const t = sv('text', { x: p.x + 10, y: p.y + p.w - 8, 'font-size': 26,
          fill: '#4c1d95' });
        t.textContent = '↕trim';
        svg.append(t);
      }
    }
  }

  // Hatch every square inch that is not a part: the strip-end offcut, the sliver
  // beside a part narrower than its strip, and the band left after the last rip.
  // The server computes these and part + waste + kerf sums exactly to the sheet.
  const WASTE_LABEL = { offcut: 'strip offcut', trim: 'waste beside a trimmed part',
                       edge: 'left over after the last rip' };
  for (const r of sh.waste) {
    const g = sv('g', {});
    g.append(sv('rect', { x: r.x, y: r.y, width: r.w, height: r.h,
      fill: 'url(#hatch)', opacity: 0.55 }));
    const tip = sv('title', {});
    tip.textContent = `${WASTE_LABEL[r.kind] || r.kind}: ` +
      `${fmt(r.w)} x ${fmt(r.h)} = ${(r.w * r.h / 1024).toFixed(1)} sq in`;
    g.append(tip);
    svg.append(g);
  }



  for (const c of sh.cuts) {
    const colour = c.saw === 'track' ? 'var(--track)' : 'var(--mitre)';
    const a = { stroke: c.type === 'trim' ? 'var(--trim)' : colour,
      'stroke-width': c.type === 'rip' ? 5 : 3.5, 'stroke-linecap': 'round' };
    if (c.type === 'cross') a['stroke-dasharray'] = '18 12';
    if (c.type === 'trim') a['stroke-dasharray'] = '5 9';
    if (c.orient === 'along')
      svg.append(sv('line', { x1: c.from, y1: c.at, x2: c.to, y2: c.at, ...a }));
    else
      svg.append(sv('line', { x1: c.at, y1: c.from, x2: c.at, y2: c.to, ...a }));
  }

  const lab = (x, y, s, anchor = 'middle', size = 34) => {
    const t = sv('text', { x, y, 'text-anchor': anchor, 'font-size': size,
      fill: '#666' }); t.textContent = s; return t;
  };
  svg.append(lab(W / 2, -8, `${sh.along_in}"`));
  const yl = lab(-8, H / 2, `${sh.across_in}"`, 'middle');
  yl.setAttribute('transform', `rotate(-90 -8 ${H / 2})`);
  svg.append(yl);

  const c = sh.counts;
  return el('div', { class: 'sheet' },
    el('div', { class: 'spread', style: 'margin-bottom:6px' },
      el('div', {}, el('b', {}, `Sheet ${pos + 1} of ${S.layout.sheets.length}`),
        el('span', { class: 'muted small' },
          ` · ${sh.thickness}" ply · ${sh.along_in}×${sh.across_in}"` +
          (sh.swapped ? ' · rips run the short way' : ''))),
      el('div', { class: 'small muted mono' },
        `${(sh.utilisation * 100).toFixed(0)}% used · ${c.n_rips} rips · ` +
        `${c.n_cross} mitre · ${c.n_wide_cross} track crosscuts` +
        (c.n_trims ? ` · ${c.n_trims} trims` : ''))),
    svg);
}

function renderCuts() {
  const host = $('#cutlist'); host.textContent = '';
  for (const p of S.layout.rip_plan) {
    const sh = S.layout.sheets.find(s => s.index === p.sheet);
    const card = el('div', { class: 'card' },
      el('div', { class: 'spread' },
        el('b', {}, `Sheet ${p.position + 1} of ${S.layout.rip_plan.length}`),
        el('span', { class: 'small muted' }, `${p.thickness}" ply`)));
    for (const g of p.groups) {
      const strips = sh.strips.filter(s => s.width === g.width);
      card.append(el('div', { style: 'margin:9px 0 3px' },
        el('i', { class: 'sw', style:
          `background:${widthColor(g.color)};display:inline-block;margin-right:6px` }),
        el('b', {}, `RIP ${g.count} strip${g.count > 1 ? 's' : ''} @ ${fmt(g.width)}`),
        el('span', { class: 'small', style: `margin-left:8px;color:${
          g.reuses_stop ? 'var(--good)' : 'var(--warn)'}` },
          g.reuses_stop ? 'stop already set' : 'move the stop'),
        el('span', { class: 'small muted', style: 'margin-left:8px' },
          `→ crosscut on ${g.saw === 'track' ? 'TRACK SAW (too wide for mitre)' : 'mitre saw'}`)));
      for (const st of strips) {
        const runs = [];
        for (const q of st.parts) {
          const last = runs[runs.length - 1];
          if (last && last.len === q.len && last.trim === q.trim) last.n++;
          else runs.push({ len: q.len, n: 1, trim: q.trim, to: q.trim_to });
        }
        card.append(el('div', { class: 'small mono', style: 'margin-left:22px' },
          runs.map(r => `${r.n}× ${fmt(r.len)}${r.trim ? ` +trim to ${fmt(r.to)}` : ''}`)
            .join(',  ') +
          (st.offcut > 0 ? `   [offcut ${fmt(st.offcut)}]` : '   [exact]')));
      }
    }
    host.append(card);
  }
}

